import { describe, expect, it } from "vitest";

import { mediaKey } from "./adapter";
import { s3Storage } from "./s3";
import { signRequest } from "./sigv4";

/**
 * The S3 adapter against a real S3-compatible server, because the thing worth proving is
 * the signature — and a mock would happily accept one that Cloudflare rejects. MinIO
 * verifies SigV4 strictly, so a passing round-trip here means R2 will accept the same bytes.
 *
 *   docker compose --profile storage up -d storage
 *
 * Skipped, not failed, when that container is not running: a contributor without Docker
 * still gets a green suite.
 */
const endpoint = process.env.S3_TEST_ENDPOINT ?? "http://localhost:9000";
const credentials = {
  accessKeyId: process.env.S3_TEST_ACCESS_KEY ?? "mimnets",
  secretAccessKey: process.env.S3_TEST_SECRET_KEY ?? "mimnets-secret",
};
const bucket = "mimnets-test";

const reachable = await fetch(`${endpoint}/minio/health/live`, {
  signal: AbortSignal.timeout(1500),
})
  .then((response) => response.ok)
  .catch(() => false);

const suite = reachable ? describe : describe.skip;

/** Creating the bucket signs a request too, so setup exercises the same code path. */
async function ensureBucket() {
  const url = new URL(`${endpoint}/${bucket}`);
  const headers = signRequest({
    method: "PUT",
    url,
    region: "auto",
    service: "s3",
    credentials,
  });
  const response = await fetch(url, { method: "PUT", headers });
  // 409 is "you already made this bucket", which is exactly what we wanted.
  if (!response.ok && response.status !== 409) {
    throw new Error(`Could not create the test bucket (${response.status}): ${await response.text()}`);
  }
}

const storage = s3Storage({ bucket, endpoint, ...credentials });
const bytes = (text: string) => new TextEncoder().encode(text);

suite("the S3 adapter against a real bucket", () => {
  it("is talking to a server that verifies signatures", async () => {
    await ensureBucket();

    const wrong = s3Storage({
      bucket,
      endpoint,
      accessKeyId: credentials.accessKeyId,
      secretAccessKey: "not-the-secret",
    });

    // If this passed, the suite below would prove nothing at all.
    await expect(
      wrong.put(mediaKey("x.png", "image/png"), bytes("x"), { contentType: "image/png" }),
    ).rejects.toThrow(/Upload failed \(403\)/);
  });

  it("round-trips a file, content type intact", async () => {
    await ensureBucket();
    const key = mediaKey("round trip.png", "image/png");

    await storage.put(key, bytes("pretend png bytes"), { contentType: "image/png" });
    const found = await storage.get(key);

    expect(new TextDecoder().decode(found?.body)).toBe("pretend png bytes");
    expect(found?.contentType).toBe("image/png");
  });

  it("returns null for a key that was never written", async () => {
    await ensureBucket();
    expect(await storage.get(mediaKey("never.png", "image/png"))).toBeNull();
  });

  it("deletes, and deleting twice is not an error", async () => {
    await ensureBucket();
    const key = mediaKey("delete-me.png", "image/png");

    await storage.put(key, bytes("x"), { contentType: "image/png" });
    await storage.delete(key);
    expect(await storage.get(key)).toBeNull();
    await expect(storage.delete(key)).resolves.toBeUndefined();
  });

  it("refuses an unsafe key before it reaches the network", async () => {
    // Keys are always generated by mediaKey, which slugs a filename down to the safe set.
    // Anything else arrived from somewhere it should not have, so it never gets signed.
    await expect(
      storage.put("../../other-bucket/x.png", bytes("x"), { contentType: "image/png" }),
    ).rejects.toThrow(/unsafe storage key/);
    await expect(storage.get("2026/08/a file.png")).rejects.toThrow(/unsafe storage key/);
  });

  it("serves from a public domain when the Site has one", () => {
    const cdn = s3Storage({ bucket, endpoint, ...credentials, publicBaseUrl: "https://cdn.example.com" });
    expect(cdn.url("2026/08/a-abc123.png")).toBe("https://cdn.example.com/2026/08/a-abc123.png");
  });

  it("falls back to the Site's own route when the bucket is private", () => {
    expect(storage.url("2026/08/a-abc123.png")).toBe("/media/2026/08/a-abc123.png");
  });
});
