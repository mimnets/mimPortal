import { describe, expect, it } from "vitest";
import { completeTheme } from "@mimnets/core";

import { theme } from "../theme";

/**
 * The Site's own Theme, held to the standard the Editor promises for it.
 *
 * The settings panel tells an Author that "nothing here can be off-brand" while offering
 * Block tones drawn from this file — so that promise is only kept if the colours it derives
 * are readable. The accent shipped in the Starter is #e05a26, which is 3.7:1 on white and
 * below what body text needs. This is the guard against that coming back, whether by a Theme
 * edited here or one generated by a model.
 */
function ratio(a: string, b: string): number {
  const luminance = (hex: string) => {
    const channel = (pair: string) => {
      const value = parseInt(pair, 16) / 255;
      return value <= 0.03928 ? value / 12.92 : Math.pow((value + 0.055) / 1.055, 2.4);
    };
    return (
      0.2126 * channel(hex.slice(1, 3)) +
      0.7152 * channel(hex.slice(3, 5)) +
      0.0722 * channel(hex.slice(5, 7))
    );
  };

  const [light, dark] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (light + 0.05) / (dark + 0.05);
}

describe("this Site's Theme", () => {
  const { colors } = completeTheme(theme);

  it("derives a readable accent, which the raw brand colour is not", () => {
    expect(ratio(colors.accent, colors.background)).toBeLessThan(4.5);
    expect(ratio(colors.accentText, colors.background)).toBeGreaterThanOrEqual(4.5);
  });

  it("derives a readable primary", () => {
    expect(ratio(colors.primaryText, colors.background)).toBeGreaterThanOrEqual(4.5);
  });

  it("sets body text well clear of the threshold", () => {
    expect(ratio(colors.text, colors.background)).toBeGreaterThanOrEqual(7);
  });

  it("keeps text legible on every band a Section can paint", () => {
    expect(ratio(colors.onPrimary, colors.primary)).toBeGreaterThanOrEqual(4.5);
    // "dark" inverts the palette, so the text colour becomes the ground.
    expect(ratio(colors.background, colors.text)).toBeGreaterThanOrEqual(4.5);
  });
});
